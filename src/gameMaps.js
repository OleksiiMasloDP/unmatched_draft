export function makeMap({
  id,
  name,
  image,
  width,
  height,
  radius,
  spaces,
  links,
  locks = [],
  bonus = [],
  tokenSlots = [],
  oneWay = [],
  starts,
}) {
  const list = spaces.map(([spaceId, x, y, zones]) => ({
    id: spaceId,
    x,
    y,
    zones,
    links: [],
    moves: [],
    secret: [],
    lock: locks.flat().includes(spaceId),
    bonusTo: [],
  }));
  const byId = new Map(list.map((space) => [space.id, space]));
  for (const [a, b] of links) {
    byId.get(a).links.push(b);
    byId.get(b).links.push(a);
    byId.get(a).moves.push(b);
    byId.get(b).moves.push(a);
  }
  for (const [from, to] of oneWay) {
    byId.get(from).links.push(to);
    byId.get(to).links.push(from);
    byId.get(from).moves.push(to);
  }
  const groups = Array.isArray(locks[0]) ? locks : [locks];
  for (const group of groups) {
    for (const a of group) {
      byId.get(a).secret = group.filter((b) => b !== a);
    }
  }
  for (const [from, to] of bonus) byId.get(from).bonusTo.push(to);
  const tokens = tokenSlots.map(([kind, space, x, y]) => ({
    kind,
    space,
    x,
    y,
  }));
  return {
    id,
    name,
    image,
    width,
    height,
    radius,
    spaces: list,
    starts,
    tokenSlots: tokens,
  };
}

